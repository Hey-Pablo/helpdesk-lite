create table public.filiais (id bigint generated by default as identity primary key, nome text not null unique);
create table public.categorias (id bigint generated by default as identity primary key, nome text not null unique);
create table public.perfis (
 id uuid primary key references auth.users(id) on delete cascade,
 nome text not null, papel text not null default 'solicitante' check (papel in ('solicitante','atendente','admin')),
 filial_id bigint references public.filiais(id)
);
create table public.sla_regras (prioridade text primary key check (prioridade in ('baixa','media','alta','critica')), horas integer not null check (horas > 0));
create table public.chamados (
 id bigint generated by default as identity primary key, titulo text not null check (length(trim(titulo)) > 0),
 descricao text not null check (length(trim(descricao)) > 0), categoria_id bigint not null references public.categorias(id),
 prioridade text not null references public.sla_regras(prioridade),
 status text not null default 'aberto' check (status in ('aberto','em_atendimento','aguardando_usuario','resolvido','fechado','reaberto')),
 solicitante_id uuid not null references public.perfis(id), atendente_id uuid references public.perfis(id),
 criado_em timestamptz not null default now(), prazo_em timestamptz not null, resolvido_em timestamptz
);
create table public.comentarios (
 id bigint generated by default as identity primary key, chamado_id bigint not null references public.chamados(id),
 autor_id uuid not null references public.perfis(id), texto text not null check (length(trim(texto)) > 0),
 interno boolean not null default false, criado_em timestamptz not null default now()
);
create table public.historico (
 id bigint generated by default as identity primary key, chamado_id bigint not null references public.chamados(id),
 autor_id uuid references public.perfis(id), status_anterior text, status_novo text not null, criado_em timestamptz not null default now()
);
create index chamados_solicitante_idx on public.chamados(solicitante_id);
create index comentarios_chamado_idx on public.comentarios(chamado_id);
create index historico_chamado_idx on public.historico(chamado_id);

-- O papel vem de tabela controlada pelo administrador, não de metadados editáveis do usuário.
create function public.equipe() returns boolean language sql stable security definer set search_path = '' as $$
 select exists (select 1 from public.perfis where id = (select auth.uid()) and papel in ('atendente','admin'))
$$;
create function public.admin() returns boolean language sql stable security definer set search_path = '' as $$
 select exists (select 1 from public.perfis where id = (select auth.uid()) and papel = 'admin')
$$;
revoke all on function public.equipe(), public.admin() from public;
grant execute on function public.equipe(), public.admin() to authenticated;
create function public.calcular_prazo() returns trigger language plpgsql set search_path = '' as $$
begin
 select new.criado_em + make_interval(hours => horas) into strict new.prazo_em from public.sla_regras where prioridade = new.prioridade;
 return new;
end $$;
create trigger chamado_prazo before insert on public.chamados for each row execute function public.calcular_prazo();

