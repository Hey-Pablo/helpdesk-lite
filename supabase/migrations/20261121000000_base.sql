create policy filiais_admin on public.filiais for all to authenticated using ((select public.admin())) with check ((select public.admin()));
create policy categorias_admin on public.categorias for all to authenticated using ((select public.admin())) with check ((select public.admin()));
create policy sla_admin on public.sla_regras for all to authenticated using ((select public.admin())) with check ((select public.admin()));
create policy perfis_leitura on public.perfis for select to authenticated using (id = (select auth.uid()) or (select public.equipe()));
create policy perfis_admin on public.perfis for all to authenticated using ((select public.admin())) with check ((select public.admin()));
create policy chamados_leitura on public.chamados for select to authenticated using (solicitante_id = (select auth.uid()) or (select public.equipe()));
create policy chamados_criacao on public.chamados for insert to authenticated with check (solicitante_id = (select auth.uid()) and status = 'aberto' and atendente_id is null and resolvido_em is null);
create policy chamados_equipe on public.chamados for update to authenticated using ((select public.equipe())) with check ((select public.equipe()));
create policy comentarios_leitura on public.comentarios for select to authenticated using (
 (select public.equipe()) or (not interno and exists (select 1 from public.chamados where id = chamado_id and solicitante_id = (select auth.uid())))
);
create policy comentarios_criacao on public.comentarios for insert to authenticated with check (
 autor_id = (select auth.uid()) and ((select public.equipe()) or (not interno and exists (select 1 from public.chamados where id = chamado_id and solicitante_id = (select auth.uid()))))
);
create policy historico_leitura on public.historico for select to authenticated using (exists (select 1 from public.chamados where id = chamado_id));
create policy historico_equipe on public.historico for insert to authenticated with check ((select public.equipe()) and autor_id = (select auth.uid()));
