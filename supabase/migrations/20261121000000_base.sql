-- Cada visão executa com os privilégios e as políticas do usuário que consulta.
create view public.painel_resumo with (security_invoker = true) as
 select count(*) filter (where status not in ('resolvido','fechado')) as abertos,
 avg(resolvido_em - criado_em) filter (where resolvido_em is not null) as tempo_medio,
 100.0 * count(*) filter (where resolvido_em <= prazo_em) / nullif(count(*) filter (where resolvido_em is not null), 0) as percentual_no_prazo from public.chamados;
create view public.painel_por_categoria with (security_invoker = true) as
 select categoria_id, count(*) as total from public.chamados group by categoria_id;
create view public.painel_por_atendente with (security_invoker = true) as
 select atendente_id, count(*) as total from public.chamados group by atendente_id;
grant select on public.painel_resumo, public.painel_por_categoria, public.painel_por_atendente to authenticated;
